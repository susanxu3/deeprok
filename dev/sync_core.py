#!/usr/bin/env python3
"""Copy the inference path from the research repo into ``src/tprok/_core/``.

The packaged tool must produce the same calls as the cluster pipeline
(``cluster/redecode_keephyp666_stats.sbatch``), so the decoder, model and ranker
code is copied verbatim rather than rewritten. Only the imports change:

  * ``from hmm_prokaryotic import X`` / ``from tools.start_ranker import X``
    -> ``from .hmm_prokaryotic import X`` / ``from .start_ranker import X``
  * ``sys.path.insert(0, str(ROOT))`` -> ``pass`` (an installed package must not
    put its own directory on ``sys.path``)
  * the four helpers the pipeline needs from ``run_viterbi_annotation.py`` (which
    itself imports matplotlib and the evaluation code) are extracted into
    ``_core/inference.py``.

Run from the repo root after any change to these modules, then re-run the
package tests (``tests/test_core_in_sync.py`` fails when ``_core`` is stale)::

    python package/dev/sync_core.py
"""
from __future__ import annotations

import ast
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
CORE = REPO / "package" / "src" / "tprok" / "_core"

# research path -> module name inside _core
MODULES = {
    "annotation_gtf.py": "annotation_gtf",
    "dataset.py": "dataset",
    "dataset_v4.py": "dataset_v4",
    "genome_sequences.py": "genome_sequences",
    "hmm_prokaryotic.py": "hmm_prokaryotic",
    "viterbi_decode.py": "viterbi_decode",
    "hmm_duration_decode.py": "hmm_duration_decode",
    "hmm_posterior_utils.py": "hmm_posterior_utils",
    "model_v4.py": "model_v4",
    "tools/start_ranker.py": "start_ranker",
    "tools/rbs_start_prior.py": "rbs_start_prior",
    "tools/prodigal_rbs_bins.py": "prodigal_rbs_bins",
    "tools/filter_nested_antisense.py": "filter_nested_antisense",
    "tools/decode_from_nn_probs.py": "decode_from_nn_probs",
}
# helpers lifted out of run_viterbi_annotation.py into _core/inference.py
INFERENCE_FUNCS = ["_nn_probs_manifest_path", "_load_nn_probs_from_cache", "_pick_device", "tile_predict_v4", "_load_checkpoint",
                   "_gene_ov_bp", "_start_codon_interval", "prodigal_overlap_filter"]
INFERENCE_HEADER = '''"""Helpers extracted verbatim from run_viterbi_annotation.py by dev/sync_core.py.

Generated file -- edit the research repo and re-sync instead.
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Dict, List, Tuple

import numpy as np
import torch

from .hmm_posterior_utils import tile_predict_v4_distribution
from .model_v4 import ProkaryoticModelV4, load_prokaryotic_model_v4_from_checkpoint

'''
GENERATED = "# Generated by package/dev/sync_core.py from {src} -- do not edit here.\n"

LOCAL = set(MODULES.values()) | {"run_viterbi_annotation", "inference"}


def rewrite(text: str) -> str:
    def sub_from(m: re.Match) -> str:
        indent, mod, rest = m.group(1), m.group(2), m.group(3)
        name = mod.split(".", 1)[1] if mod.startswith("tools.") else mod
        if name == "run_viterbi_annotation":
            name = "inference"
        if name.split(".")[0] not in LOCAL and not mod.startswith("tools."):
            return m.group(0)
        return f"{indent}from .{name} import{rest}"

    text = re.sub(r"^([ \t]*)from ([A-Za-z_][\w.]*) import(.*)$", sub_from, text, flags=re.M)

    def sub_import(m: re.Match) -> str:
        indent, mod, alias = m.group(1), m.group(2), m.group(3) or ""
        if mod not in LOCAL:
            return m.group(0)
        return f"{indent}from . import {mod}{alias}"

    text = re.sub(r"^([ \t]*)import ([A-Za-z_]\w*)( as \w+)?[ \t]*$", sub_import, text, flags=re.M)
    text = text.replace("sys.path.insert(0, str(ROOT))", "pass")
    return text


def extract_functions(src: Path, names: list[str]) -> str:
    text = src.read_text()
    tree = ast.parse(text)
    found = {}
    for node in tree.body:
        if isinstance(node, ast.FunctionDef) and node.name in names:
            found[node.name] = ast.get_source_segment(text, node)
    missing = [n for n in names if n not in found]
    if missing:
        raise SystemExit(f"{src}: functions not found: {missing}")
    return "\n\n\n".join(found[n] for n in names) + "\n"


def build() -> dict[str, str]:
    """Return {filename: content} for every generated _core file."""
    out = {}
    for rel, name in MODULES.items():
        src = REPO / rel
        out[f"{name}.py"] = GENERATED.format(src=rel) + rewrite(src.read_text())
    inf = INFERENCE_HEADER + extract_functions(REPO / "run_viterbi_annotation.py", INFERENCE_FUNCS)
    out["inference.py"] = GENERATED.format(src="run_viterbi_annotation.py") + inf
    out["__init__.py"] = GENERATED.format(src="(package)") + (
        '"""Inference code copied from the research repo; see dev/sync_core.py."""\n')
    return out


def main() -> None:
    check = "--check" in sys.argv
    files = build()
    stale = []
    CORE.mkdir(parents=True, exist_ok=True)
    for fn, content in files.items():
        p = CORE / fn
        if check:
            if not p.exists() or p.read_text() != content:
                stale.append(fn)
        else:
            p.write_text(content)
    if check:
        if stale:
            raise SystemExit(f"_core is stale: {stale} -- run package/dev/sync_core.py")
        print("_core in sync")
    else:
        print(f"wrote {len(files)} files to {CORE}")


if __name__ == "__main__":
    main()
